#Diferentemente das listas, as tuplas possuem parênteses ao invés de colchetes:
###lista = [1, 2, 3, 4, 5]
###tupla = (1, 2, 3, 4, 5)

#Outra característica principal é que as tuplas são imutáveis, tanto nos seus valores quanto em tamanho/posição.
#Para fazer alterações, é necessário criar uma nova tupla com base na antiga:
###tupla = (1, 2, 3)
###nova_tupla = tupla + (4,)             -> a vírgula após o 4 é necessária para que o python entenda que se trata de uma tupla